#!/usr/bin/env python3
"""Validate and normalize links in Rust skills for .agents/skills/"""

from pathlib import Path
import re
import sys

SKILLS_DIR = Path(r"E:\gemini\agent_setup\.agents\skills")

def update_rust_best_practices():
    path = SKILLS_DIR / "rust-best-practices" / "SKILL.md"
    content = path.read_text(encoding="utf-8")
    
    # Update lints mention to point to local resources/lints
    old_text = "suggest `lints/lints.toml` and\n  `lints/clippy.toml` from https://github.com/morganlinton/BeautifulRust"
    new_text = "suggest `resources/lints/lints.toml` and\n  `resources/lints/clippy.toml` (bundled in this skill, or from https://github.com/morganlinton/BeautifulRust)"
    
    if old_text in content:
        content = content.replace(old_text, new_text)
    elif "resources/lints/lints.toml" not in content:
        content = content.replace("suggest `lints/lints.toml`", "suggest `resources/lints/lints.toml`")
        content = content.replace("`lints/clippy.toml`", "`resources/lints/clippy.toml`")

    path.write_text(content, encoding="utf-8")
    print(f"Updated {path}")

def update_rust_review():
    path = SKILLS_DIR / "rust-review" / "SKILL.md"
    content = path.read_text(encoding="utf-8")
    
    # Update bevy reference
    content = content.replace(
        "(`bevy.md`) in the `rust-best-practices` skill's references first.",
        "(`bevy.md` at `../rust-best-practices/references/bevy.md`) in the `rust-best-practices` skill first."
    )
    
    # Update references mention
    content = content.replace(
        "The `rust-best-practices` skill and its `references/` folder hold the full rules",
        "The `rust-best-practices` skill and its `references/` folder (`../rust-best-practices/references/`) hold the full rules"
    )
    
    # Add example reference
    if "examples/review-inventory.md" not in content:
        content = content.replace(
            "## 5. Offer the lints",
            "## Example Review Report\n\nSee `examples/review-inventory.md` for a complete, realistic review report generated by this skill.\n\n## 5. Offer the lints"
        )
        
    # Update lints offer mention
    content = content.replace(
        "(`lints/lints.toml` and `lints/clippy.toml` in the BeautifulRust repo,",
        "(`../rust-best-practices/resources/lints/lints.toml` and `clippy.toml`, or in the BeautifulRust repo,"
    )

    path.write_text(content, encoding="utf-8")
    print(f"Updated {path}")

def update_rust_port():
    path = SKILLS_DIR / "rust-port" / "SKILL.md"
    content = path.read_text(encoding="utf-8")
    
    content = content.replace(
        "follow the `rust-best-practices` skill if it is\ninstalled.",
        "follow the `rust-best-practices` skill (`../rust-best-practices/SKILL.md`) if it is\ninstalled."
    )
    
    path.write_text(content, encoding="utf-8")
    print(f"Updated {path}")

def validate_skills():
    errors = 0
    skills = ["rust-best-practices", "rust-review", "rust-port"]
    
    for skill in skills:
        skill_dir = SKILLS_DIR / skill
        skill_md = skill_dir / "SKILL.md"
        if not skill_md.exists():
            print(f"ERROR: Missing SKILL.md in {skill_dir}")
            errors += 1
            continue
            
        text = skill_md.read_text(encoding="utf-8")
        
        # Check YAML frontmatter
        if not text.startswith("---"):
            print(f"ERROR: {skill_md} missing YAML frontmatter start '---'")
            errors += 1
        else:
            parts = text.split("---", 2)
            if len(parts) < 3:
                print(f"ERROR: {skill_md} malformed YAML frontmatter")
                errors += 1
            else:
                fm = parts[1]
                if f"name: {skill}" not in fm and f"name:\n  {skill}" not in fm:
                    print(f"ERROR: {skill_md} YAML frontmatter missing correct name: {skill}")
                    errors += 1
                if "description:" not in fm:
                    print(f"ERROR: {skill_md} YAML frontmatter missing description")
                    errors += 1
                    
        # Check referenced files inside backticks
        ref_files = re.findall(r"`([a-zA-Z0-9_\-\./]+\.(?:md|toml))`", text)
        for rf in ref_files:
            # Ignore external URL or generic terms
            if "/" in rf and not rf.startswith("http"):
                target = (skill_dir / rf).resolve()
                if not target.exists():
                    # check if it is a relative path to workspace
                    print(f"WARNING: Link '{rf}' referenced in {skill}/SKILL.md does not exist at {target}")
                else:
                    print(f"OK: Link '{rf}' in {skill} -> {target.name}")
                    
    print(f"\nValidation finished with {errors} errors.")
    return errors

if __name__ == "__main__":
    update_rust_best_practices()
    update_rust_review()
    update_rust_port()
    errs = validate_skills()
    sys.exit(errs)
